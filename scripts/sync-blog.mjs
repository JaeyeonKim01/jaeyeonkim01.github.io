import { readFile, writeFile, mkdir, copyFile, readdir } from 'node:fs/promises';
import katex from 'katex';

function renderMath(html) {
  return html.replace(/\\\[([\s\S]*?)\\\]|\\\(([\s\S]*?)\\\)/g, (_, display, inline) =>
    katex.renderToString(display ?? inline, {
      displayMode: display !== undefined,
      throwOnError: true,
      strict: 'error',
      trust: false,
      output: 'htmlAndMathml',
    })
  );
}

const manifest = JSON.parse(await readFile(new URL('../posts/index.json', import.meta.url), 'utf8'));
const posts = await Promise.all(manifest.map(async ({file, ...post}) => {
  if (!/^[a-z0-9-]+\.html$/.test(file)) throw new Error(`Invalid post file: ${file}`);
  return {...post, html: renderMath(await readFile(new URL(`../posts/${file}`, import.meta.url), 'utf8'))};
}));
const content = `/* Generated by npm run build:blog; edit posts/ instead. */\nwindow.BLOG_POSTS = ${JSON.stringify(posts, null, 2)};\n`;
const output = new URL('../dist/posts.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Blog output is stale. Run npm run build:blog.');
} else {
  const vendor = new URL('../dist/assets/katex/', import.meta.url);
  const katexDist = new URL('../node_modules/katex/dist/', import.meta.url);
  await mkdir(new URL('fonts/', vendor), {recursive: true});
  const css = (await readFile(new URL('katex.min.css', katexDist), 'utf8'))
    .replace(/,url\([^)]*\.(?:woff|ttf)["']?\)\s*format\([^)]*\)/g, '');
  await writeFile(new URL('katex.min.css', vendor), css);
  await copyFile(new URL('../node_modules/katex/LICENSE', import.meta.url), new URL('LICENSE', vendor));
  for (const font of await readdir(new URL('fonts/', katexDist))) {
    if (font.endsWith('.woff2')) await copyFile(new URL(`fonts/${font}`, katexDist), new URL(`fonts/${font}`, vendor));
  }
  await writeFile(output, content);
}
